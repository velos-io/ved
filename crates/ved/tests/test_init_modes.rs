#[test]
fn test_init_compose_subcommand_conversion() {
    let tmp = std::env::temp_dir().join(format!("init_test_compose_{}", std::process::id()));
    let _ = fs::create_dir_all(&tmp);

    let compose_content = r#"
version: '3.8'
services:
  web:
    image: nginx:alpine
    ports:
      - "8080:80"
    depends_on:
      - db
    healthcheck:
      test: ["CMD-SHELL", "wget -qO- http://localhost:80/ || exit 1"]
  db:
    image: postgres:16-alpine
    ports:
      - "5432:5432"
    environment:
      POSTGRES_DB: app_db
"#;
    let compose_file = tmp.join("docker-compose.yml");
    fs::write(&compose_file, compose_content).unwrap();

    let ved_bin = env!("CARGO_BIN_EXE_ved");
    let output = support::command(ved_bin, &tmp)
        .arg("init")
        .arg("--compose")
        .current_dir(&tmp)
        .output()
        .expect("Failed to execute ved init --compose");

    assert!(
        output.status.success(),
        "Stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );

    let vedfile = tmp.join("Vedfile");
    assert!(vedfile.exists(), "Vedfile should have been generated");

    let content = fs::read_to_string(&vedfile).unwrap();
    assert!(content.contains("name=\"web\""));
    assert!(content.contains("name=\"db\""));
    assert!(content.contains("image=\"nginx:alpine\""));
    assert!(content.contains("image=\"postgres:16-alpine\""));
    assert!(content.contains("wait_for=[\"db.healthy\"]"));
    assert!(content.contains("Port(80, host=8080)"));

    let eval_res = ved_core::load_starlark_spec(&vedfile);
    assert!(
        eval_res.is_ok(),
        "Generated Vedfile failed to evaluate: {:?}",
        eval_res.err()
    );

    let dot_ved_compose = tmp.join(".ved/docker-compose.yml");
    assert!(
        !dot_ved_compose.exists(),
        ".ved/docker-compose.yml should not exist prior to compile/ps"
    );

    let ps_output = support::command(ved_bin, &tmp)
        .arg("ps")
        .env_remove("TARGET")
        .env_remove("DEPLOYMENT_TARGET")
        .current_dir(&tmp)
        .output()
        .expect("Failed to execute ved ps");
    assert!(
        ps_output.status.success(),
        "Stderr: {}",
        String::from_utf8_lossy(&ps_output.stderr)
    );
    let stdout = String::from_utf8_lossy(&ps_output.stdout);
    assert!(stdout.contains("hint: deployment assets missing or outdated"));
    assert!(
        dot_ved_compose.exists(),
        ".ved/docker-compose.yml should have been implicitly generated by ved ps"
    );
    let calls = fs::read_to_string(tmp.join("test-tools.log")).unwrap();
    assert!(calls.contains("docker\n"), "{calls}");
    assert!(calls.contains("ps\n"), "{calls}");

    let _ = fs::remove_dir_all(&tmp);
}

